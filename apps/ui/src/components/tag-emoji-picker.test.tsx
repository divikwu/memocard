// @vitest-environment jsdom
import { cleanup, fireEvent, render, screen } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { afterEach, beforeEach, expect, it, vi } from "vitest";
import TagEmojiPicker from "./tag-emoji-picker";
beforeEach(() => { vi.stubGlobal("ResizeObserver", class { observe() {} unobserve() {} disconnect() {} }); });
afterEach(cleanup);
it("searches Chinese names across categories and returns the native emoji", async () => {
  const onSelect = vi.fn();
  const user = userEvent.setup();
  render(<TagEmojiPicker selected="🎨" onSelect={onSelect} />);
  const categories = screen.getAllByRole("button", { name: /Emoji 分类：/ });
  expect(screen.getByLabelText("Emoji 分类").className).toContain("-mx-3");
  expect(categories).toHaveLength(8);
  expect(categories[0].getAttribute("aria-pressed")).toBe("true");
  await user.hover(screen.getByRole("button", { name: "Emoji 分类：动物与自然" }));
  expect((await screen.findByText("动物与自然")).getAttribute("data-slot")).toBe("tooltip-content");
  await user.click(screen.getByRole("button", { name: "Emoji 分类：动物与自然" }));
  expect(screen.getByRole("button", { name: "Emoji 分类：动物与自然" }).getAttribute("aria-pressed")).toBe("true");
  await user.type(screen.getByRole("textbox", { name: "搜索 Emoji" }), "调色板");
  const palette = screen.getByRole("button", { name: /调色板/ });
  expect(palette.getAttribute("aria-pressed")).toBe("true");
  expect(palette.className).toContain("text-xl");
  expect(palette.className).toContain("bg-state");
  await user.click(palette);
  expect(onSelect).toHaveBeenCalledExactlyOnceWith("🎨");
  fireEvent.change(screen.getByRole("textbox", { name: "搜索 Emoji" }), { target: { value: "no-matching-emoji" } });
  expect(screen.getByRole("status").textContent).toBe("没有匹配的 Emoji");
});
it("finds a pasted emoji and accepts a custom grapheme without losing skin tones", async () => {
  const onSelect = vi.fn();
  render(<TagEmojiPicker onSelect={onSelect} />);
  const input = screen.getByRole("textbox", { name: "搜索 Emoji" });
  fireEvent.change(input, { target: { value: "🎨" } });
  fireEvent.click(screen.getByRole("button", { name: /调色板/ }));
  expect(onSelect).toHaveBeenLastCalledWith("🎨");
  fireEvent.change(input, { target: { value: "🧑🏽‍💻" } });
  fireEvent.keyDown(input, { key: "Enter", isComposing: true });
  expect(onSelect).toHaveBeenCalledTimes(1);
  fireEvent.keyDown(input, { key: "Enter" });
  expect(onSelect).toHaveBeenLastCalledWith("🧑🏽‍💻");
  fireEvent.change(input, { target: { value: "💡💡" } });
  expect(screen.queryByRole("button", { name: /使用/ })).toBeNull();
});
it("disables search, emoji selection and categories while saving", () => {
  const onSelect = vi.fn();
  render(<TagEmojiPicker disabled onSelect={onSelect} />);
  expect(screen.getByRole("textbox", { name: "搜索 Emoji" }).hasAttribute("disabled")).toBe(true);
  for (const button of screen.getAllByRole("button")) expect(button.hasAttribute("disabled")).toBe(true);
  fireEvent.click(screen.getAllByRole("button")[0]);
  expect(onSelect).not.toHaveBeenCalled();
});
