import { createRequire } from "node:module";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = fileURLToPath(new URL("..", import.meta.url));
const uiRoot = path.join(root, "apps/ui");
const require = createRequire(path.join(uiRoot, "package.json"));
const output = path.join(root, "apps/apple/Sources/SidebarPreviewPalette.generated.swift");

export async function sampleSidebarPreviewPalette() {
  const { createServer } = await import(require.resolve("vite"));
  const { chromium } = require("playwright");
  const server = await createServer({
    root: uiRoot,
    configFile: path.join(uiRoot, "ui/native/vite.palette.config.ts"),
    logLevel: "error",
    server: { host: "127.0.0.1", port: 0, strictPort: false, open: false },
  });
  let browser;
  try {
    await server.listen();
    const address = server.httpServer.address();
    if (!address || typeof address === "string") throw new Error("Palette sampler did not start.");
    browser = await chromium.launch({ headless: true });
    const page = await browser.newPage({ colorScheme: "light" });
    await page.route("**/*", route => new URL(route.request().url()).hostname === "127.0.0.1" ? route.continue() : route.abort());
    await page.goto(`http://127.0.0.1:${address.port}/ui/native/palette.html`);
    await page.waitForFunction(() => window.sidebarPaletteSampler);
    const palettes = {};
    let rowRadius;
    for (const mode of ["light", "dark"]) {
      const tokens = await page.evaluate(async mode => {
        const root = document.documentElement;
        const { readIOSPalette, readIOSThemeRadius, keys, appearance, radius } = window.sidebarPaletteSampler;
        root.dataset.uiTheme = mode;
        document.getElementById("palette-theme").dataset.uiTheme = mode;
        root.dataset.webPalette = appearance.palette;
        root.dataset.webNeutral = appearance.neutralPalette;
        root.dataset.uiAppearance = "";
        root.style.setProperty("--ui-preview-radius", radius);
        root.style.colorScheme = mode;
        await new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)));
        const palette = readIOSPalette();
        if (!palette || keys.some(key => !palette[key] || palette[key].length !== 4 || palette[key].some(value => !Number.isFinite(value) || value < 0 || value > 255))) throw new Error(`Incomplete ${mode} palette from production CSS`);
        const rowRadius = readIOSThemeRadius();
        if (!Number.isFinite(rowRadius) || rowRadius < 0) throw new Error("Invalid native radius from production CSS");
        return { palette: Object.fromEntries(keys.map(key => [key, palette[key]])), rowRadius };
      }, mode);
      palettes[mode] = tokens.palette;
      rowRadius = tokens.rowRadius;
    }
    return [
      "// Generated by scripts/generate-sidebar-preview-palette.mjs. Do not edit.",
      "// Samples production CSS and readIOSPalette with the locked Playwright Chromium.",
      "#if DEBUG && os(iOS)",
      "enum SidebarPreviewPalette {",
      `    static let rowRadius: Double = ${rowRadius}`,
      ...Object.entries(palettes).flatMap(([mode, palette]) => [
        `    static let ${mode}: [String: [Double]] = [`,
        ...Object.entries(palette).map(([key, rgba]) => `        "${key}": [${rgba.map(value => String(Number(value.toFixed(8)))).join(", ")}],`),
        "    ]",
      ]),
      "}",
      "#endif",
      "",
    ].join("\n");
  } finally {
    await browser?.close();
    await server.close();
  }
}

export async function writeSidebarPreviewPalette(swift, { check = false, outputPath = output } = {}) {
  let current;
  try { current = await readFile(outputPath, "utf8"); }
  catch (error) { if (error.code !== "ENOENT") throw error; }
  if (check) {
    if (current !== swift) throw new Error("Sidebar Preview palette is stale. Run pnpm palette:build and commit the generated Swift fixture.");
  } else if (current !== swift) {
    await writeFile(outputPath, swift);
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.slice(2).some(argument => argument !== "--check")) throw new Error("Usage: node scripts/generate-sidebar-preview-palette.mjs [--check]");
  const check = process.argv.includes("--check");
  await writeSidebarPreviewPalette(await sampleSidebarPreviewPalette(), { check });
  console.log(check ? "Sidebar Preview palette matches production CSS (default appearance, light/dark)." : "Generated SidebarPreviewPalette.generated.swift from production CSS.");
}
